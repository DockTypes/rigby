import 'dart:async';
import 'dart:io';
import 'dart:math' as dart_math;
import 'dart:convert';
import 'package:audioplayers/audioplayers.dart';
import 'package:flutter/foundation.dart' show debugPrint;
import 'package:http/http.dart' as http;
import 'package:flutter_tts/flutter_tts.dart';
import '../config/api_keys.dart';
import 'audio_visualizer.dart';

class TtsService {
  static final TtsService _instance = TtsService._internal();
  factory TtsService() => _instance;
  TtsService._internal();

  /// Synchronized with AppSettings.useLocalTts; true = device-local TTS, false = ElevenLabs cloud TTS.
  static bool useLocal = true;

  static const String _apiKey = ApiKeys.elevenLabs;
  static const String _voiceId = ApiKeys.elevenLabsVoiceId;

  final AudioPlayer _player = AudioPlayer();
  final FlutterTts _localTts = FlutterTts();
  bool _initialized = false;
  bool _isSpeaking = false;
  bool _isStoppingForRestart = false;
  // Monotonic speech token used to invalidate in-flight callbacks from superseded utterances.
  int _speakToken = 0;
  Timer? _syncTimer;
  Stopwatch? _syncStopwatch;
  StreamSubscription<PlayerState>? _stateSub;
  StreamSubscription<Duration>? _posSub;
  String? _lastTempFile;
  HttpServer? _proxyServer;
  final AudioVisualizer _visualizer = AudioVisualizer();

  Future<void> Function()? onSpeakPrepare;
  Function()? onSpeakStart;
  Function()? onSpeakDone;
  Function(double amp, double formant)? onAudioData;

  Future<void> initialize() async {
    if (_initialized) return;
    _initialized = true;

    await _player.setVolume(1.0);
    _player.onPlayerStateChanged.listen((state) {
      // Only completed state triggers finish. Stopped states can occur on transient focus loss.
      if (state == PlayerState.completed) {
        _finishSpeak(_speakToken);
        final pathToDelete = _lastTempFile;
        _lastTempFile = null;
        if (pathToDelete != null) {
          Future(() async {
            try { await File(pathToDelete).delete(); } catch (_) {}
          });
        }
      }
    });

    // Local TTS tuned for natural deep male voice
    await _localTts.setLanguage('ro-RO');
    await _localTts.setSpeechRate(0.62);
    await _localTts.setVolume(1.0);
    await _localTts.setPitch(0.78);

    await _selectBestVoice('ro');

    _localTts.setCompletionHandler(() {
      // Ignore cancellations generated by an internal restart in speak().
      if (_isStoppingForRestart) return;
      _finishSpeak(_speakToken);
    });
    _localTts.setCancelHandler(() {
      if (_isStoppingForRestart) return;
      _finishSpeak(_speakToken);
    });
    _localTts.setStartHandler(() {
      // Capture current token to auto-cancel procedural amplitude when superseded.
      final myToken = _speakToken;
      onSpeakStart?.call();
      _startProceduralAmplitude(myToken);
    });
  }

  // Single dispatch point for onSpeakDone, guarded against duplicate callbacks by speech token.
  void _finishSpeak(int token) {
    if (token != _speakToken) return;
    if (!_isSpeaking) return;
    _isSpeaking = false;
    _syncTimer?.cancel();
    _syncStopwatch?.stop();
    _visualizer.stop();
    _proxyServer?.close(force: true);
    _proxyServer = null;
    onAudioData?.call(0.0, 0.5);
    onSpeakDone?.call();
  }

  // Always updates the local TTS engine so it's ready if the user switches from ElevenLabs to local mode.
  Future<void> applyLocale(String locale) async {
    if (!_initialized) return;
    await _localTts.setLanguage(locale.replaceAll('_', '-'));
    await _selectBestVoice(locale.substring(0, 2).toLowerCase());
  }

  Future<void> _selectBestVoice(String langPrefix) async {
    try {
      final voices = await _localTts.getVoices as List?;
      if (voices != null) {
        final best = voices.where((v) {
          final name = (v['name'] ?? '').toString().toLowerCase();
          final loc = (v['locale'] ?? '').toString().toLowerCase();
          return loc.startsWith(langPrefix) && name.contains('goog');
        }).toList();
        if (best.isNotEmpty) {
          await _localTts.setVoice({
            'name': best.first['name'],
            'locale': best.first['locale'],
          });
        }
      }
    } catch (_) {}
  }

  Future<void> stop() async {
    if (!_initialized) return;
    // Bump token to invalidate in-flight async callbacks.
    _speakToken++;
    _isSpeaking = false;
    _syncTimer?.cancel();
    _syncStopwatch?.stop();
    _stateSub?.cancel();
    _stateSub = null;
    _posSub?.cancel();
    _posSub = null;
    await _proxyServer?.close(force: true);
    _proxyServer = null;
    _visualizer.stop();
    onAudioData?.call(0.0, 0.5);
    if (useLocal) {
      await _localTts.stop();
    } else {
      await _player.stop();
    }
  }

  Future<void> speak(String rawText) async {
    if (!_initialized) {
      await initialize();
    }

    // Sanitize text from markdown asterisks and quotation marks that can glitch TTS engines.
    final text = rawText
        .replaceAll('*', '')
        .replaceAll('"', '')
        .replaceAll('„', '')
        .replaceAll('”', '')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();

    // Flag prevents the internal stop() from firing onSpeakDone before the new utterance begins.
    _isStoppingForRestart = true;
    await stop();
    _isStoppingForRestart = false;

    final myToken = ++_speakToken;

    if (onSpeakPrepare != null) {
      _isSpeaking = true;
      await onSpeakPrepare!();
      if (myToken != _speakToken) return;
      if (!_isSpeaking) return;
    }

    if (useLocal) {
      await _speakLocal(text, myToken);
    } else {
      await _speakElevenLabs(text, myToken);
    }
  }

  Future<void> _speakLocal(String text, int myToken) async {
    try {
      _isSpeaking = true;
      await _localTts.speak(text);
    } catch (e) {
      debugPrint('[TTS-Local] Error: $e');
      _finishSpeak(myToken);
    }
  }

  void _startProceduralAmplitude(int myToken) {
    _syncTimer?.cancel();
    final sw = Stopwatch()..start();
    _syncTimer = Timer.periodic(const Duration(milliseconds: 16), (t) {
      if (myToken != _speakToken || !_isSpeaking) { t.cancel(); return; }
      final sec = sw.elapsedMilliseconds / 1000.0;
      final wave = dart_math.sin(sec * 9.0) * 0.35
                 + dart_math.sin(sec * 5.5) * 0.25
                 + dart_math.sin(sec * 14.0) * 0.10
                 + dart_math.sin(sec * 45) * 0.035;
      final amp = (0.28 + wave).clamp(0.0, 1.0);
      onAudioData?.call(amp, 0.5);
    });
  }

  Future<void> _speakElevenLabs(String text, int myToken) async {
    try {
      await _proxyServer?.close(force: true);
      _proxyServer = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
      final port = _proxyServer!.port;

      // Pipe the streaming audio directly to the native player as chunks arrive.
      _proxyServer!.listen((HttpRequest request) async {
        if (request.method == 'HEAD') {
          request.response.headers.contentType = ContentType('audio', 'mpeg');
          request.response.statusCode = HttpStatus.ok;
          await request.response.close();
          return;
        }

        final client = http.Client();
        try {
          final uri = Uri.parse(
            'https://api.elevenlabs.io/v1/text-to-speech/$_voiceId/stream'
            '?optimize_streaming_latency=3&output_format=mp3_44100_128',
          );
          final clientRequest = http.Request('POST', uri)
            ..headers.addAll({
              'xi-api-key': _apiKey,
              'Content-Type': 'application/json',
              'Accept': 'audio/mpeg',
            })
            ..body = jsonEncode({
              'text': text,
              'model_id': 'eleven_multilingual_v2',
              'voice_settings': {
                'stability': 0.45,
                'similarity_boost': 0.80,
                'style': 0.30,
                'use_speaker_boost': true,
              },
            });

          final streamed = await client
              .send(clientRequest)
              .timeout(const Duration(seconds: 30));

          if (streamed.statusCode != 200) {
            debugPrint('[TTS] Stream synth failed: HTTP ${streamed.statusCode}');
            request.response.statusCode = HttpStatus.internalServerError;
            await request.response.close();
            return;
          }

          request.response.headers.contentType = ContentType('audio', 'mpeg');
          request.response.headers.chunkedTransferEncoding = true;
          await streamed.stream.pipe(request.response);
        } catch (e) {
          debugPrint('[TTS] Proxy error: $e');
          try {
            request.response.statusCode = HttpStatus.internalServerError;
            await request.response.close();
          } catch (_) {}
        } finally {
          client.close();
        }
      });

      final url = 'http://127.0.0.1:$port/stream.mp3';

      if (myToken != _speakToken) return;

      _isSpeaking = true;
      bool hasStartedPlaying = false;

      // Synchronize lip animation with actual hardware playback start, avoiding network latency offset.
      _posSub = _player.onPositionChanged.listen((p) {
        if (myToken != _speakToken || !_isSpeaking) return;
        if (p.inMilliseconds > 0 && !hasStartedPlaying) {
          hasStartedPlaying = true;
          onSpeakStart?.call();
        }
      });

      // Android Visualizer captures real speaker RMS amplitude and FFT formants for lip sync.
      _visualizer.onFft = (amp, formant) {
        if (myToken != _speakToken || !_isSpeaking) return;
        if (!hasStartedPlaying) return;
        
        // 200ms delay compensates for Android audio hardware output buffer latency.
        Future.delayed(const Duration(milliseconds: 200), () {
          if (myToken != _speakToken || !_isSpeaking) return;
          // Noise gate: silence mouth below threshold; scale down mouth movement aggressiveness.
          final cleanAmp = amp < 0.12 ? 0.0 : amp;
          onAudioData?.call(cleanAmp * 0.6, formant);
        });
      };
      _visualizer.start();

      await _player.play(UrlSource(url));
    } catch (e, st) {
      debugPrint('[TTS-ElevenLabs] Exception: $e\n$st');
      _finishSpeak(myToken);
    }
  }
}
